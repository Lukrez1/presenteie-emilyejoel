create extension if not exists pgcrypto;

create table if not exists public.gifts (
  id bigint generated by default as identity primary key,
  source_id integer unique not null,
  name text not null,
  category text not null,
  brand text,
  price numeric(12,2) not null default 0,
  quantity integer not null default 1,
  giver text,
  received boolean not null default false,
  thanked boolean not null default false,
  notes text,
  description text not null default 'Para fazer parte da nossa nova casa.',
  image_url text,
  status text not null default 'available' check (status in ('available','reserved','received')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.reservation_requests (
  id uuid primary key default gen_random_uuid(),
  request_code text unique not null default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
  gift_id bigint not null references public.gifts(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','confirmed','rejected','cancelled')),
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  confirmed_at timestamptz,
  rejected_at timestamptz
);

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists gifts_touch_updated_at on public.gifts;
create trigger gifts_touch_updated_at before update on public.gifts
for each row execute function public.touch_updated_at();

drop trigger if exists reservation_requests_touch_updated_at on public.reservation_requests;
create trigger reservation_requests_touch_updated_at before update on public.reservation_requests
for each row execute function public.touch_updated_at();

create or replace function public.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.app_admins where user_id = auth.uid());
$$;

alter table public.gifts enable row level security;
alter table public.app_admins enable row level security;
alter table public.reservation_requests enable row level security;

drop policy if exists "Public can read gifts" on public.gifts;
create policy "Public can read gifts" on public.gifts for select using (true);

drop policy if exists "Admins can update gifts" on public.gifts;
create policy "Admins can update gifts" on public.gifts for update using (public.is_app_admin()) with check (public.is_app_admin());

drop policy if exists "Admins can read requests" on public.reservation_requests;
create policy "Admins can read requests" on public.reservation_requests for select using (public.is_app_admin());

drop policy if exists "Admins can update requests" on public.reservation_requests;
create policy "Admins can update requests" on public.reservation_requests for update using (public.is_app_admin()) with check (public.is_app_admin());

drop policy if exists "Admins can read admin list" on public.app_admins;
create policy "Admins can read admin list" on public.app_admins for select using (public.is_app_admin());

create or replace function public.create_reservation_request(p_gift_id bigint)
returns table(id uuid, request_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.reservation_requests%rowtype;
begin
  if not exists(select 1 from public.gifts where gifts.id = p_gift_id and status = 'available' and received = false) then
    raise exception 'Gift is not available';
  end if;

  insert into public.reservation_requests(gift_id)
  values (p_gift_id)
  returning * into v_request;

  return query select v_request.id, v_request.request_code;
end;
$$;

grant execute on function public.create_reservation_request(bigint) to anon, authenticated;

create or replace function public.confirm_reservation_request(p_request_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_gift_id bigint;
begin
  if not public.is_app_admin() then raise exception 'Not authorized'; end if;

  select gift_id into v_gift_id
  from public.reservation_requests
  where id = p_request_id and status = 'pending'
  for update;

  if v_gift_id is null then raise exception 'Request is not pending'; end if;

  if not exists(select 1 from public.gifts where id = v_gift_id and status = 'available' for update) then
    raise exception 'Gift is not available anymore';
  end if;

  update public.reservation_requests
  set status = 'confirmed', confirmed_at = now()
  where id = p_request_id;

  update public.reservation_requests
  set status = 'rejected', rejected_at = now()
  where gift_id = v_gift_id and id <> p_request_id and status = 'pending';

  update public.gifts
  set status = 'reserved', received = false
  where id = v_gift_id;
end;
$$;

grant execute on function public.confirm_reservation_request(uuid) to authenticated;

create or replace function public.reject_reservation_request(p_request_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_app_admin() then raise exception 'Not authorized'; end if;
  update public.reservation_requests
  set status = 'rejected', rejected_at = now()
  where id = p_request_id and status = 'pending';
end;
$$;

grant execute on function public.reject_reservation_request(uuid) to authenticated;
